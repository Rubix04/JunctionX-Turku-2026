import { randomUUID } from "node:crypto";
import { createReadStream } from "node:fs";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

import sharp, { type OutputInfo } from "sharp";

import { ApiError, badRequest } from "../../errors.js";

export type Crop = { x: number; y: number; width: number; height: number };

// Profile pictures are small on screen (home, pet switcher, reminders, passport).
const PHOTO_SIZE = 512;
const ACCEPTED_FORMATS = new Set(["jpeg", "png", "webp", "heif", "avif"]);

const photoDir = (uploadDir: string) => join(uploadDir, "pet-photos");

/** Keys are generated by `storePetPhoto`, but check anyway so a bad key can't leave the folder. */
const photoPath = (uploadDir: string, key: string) => {
  if (!/^[0-9a-f-]{36}\.webp$/.test(key)) {
    throw new Error(`Invalid photo key: ${key}`);
  }
  return join(photoDir(uploadDir), key);
};

/**
 * Validates an uploaded image, applies the EXIF rotation and the optional crop
 * (in pixels of the upright image), and stores it as a square WebP. Returns the new key.
 * Re-encoding also drops EXIF metadata such as GPS location.
 */
export const storePetPhoto = async (uploadDir: string, input: Buffer, crop?: Crop) => {
  let upright: { data: Buffer; info: OutputInfo };
  try {
    const metadata = await sharp(input).metadata();
    if (!metadata.format || !ACCEPTED_FORMATS.has(metadata.format)) {
      throw badRequest("INVALID_IMAGE", "Upload a JPEG, PNG, WebP or HEIC image");
    }
    upright = await sharp(input).rotate().toBuffer({ resolveWithObject: true });
  } catch (error) {
    if (error instanceof ApiError) {
      throw error;
    }
    throw badRequest("INVALID_IMAGE", "The file is not a readable image");
  }

  let image = sharp(upright.data);
  if (crop) {
    const fits =
      crop.x + crop.width <= upright.info.width && crop.y + crop.height <= upright.info.height;
    if (!fits) {
      throw badRequest("INVALID_CROP", "The crop area is outside the image");
    }
    image = image.extract({ left: crop.x, top: crop.y, width: crop.width, height: crop.height });
  }

  const output = await image
    .resize(PHOTO_SIZE, PHOTO_SIZE, { fit: "cover" })
    .webp({ quality: 80 })
    .toBuffer();

  await mkdir(photoDir(uploadDir), { recursive: true });
  const key = `${randomUUID()}.webp`;
  await writeFile(photoPath(uploadDir, key), output);
  return key;
};

export const readPetPhoto = (uploadDir: string, key: string) =>
  createReadStream(photoPath(uploadDir, key));

/** Deletes a stored picture. Missing files are ignored. */
export const deletePetPhotoFile = async (uploadDir: string, key: string | null) => {
  if (key) {
    await rm(photoPath(uploadDir, key), { force: true });
  }
};
